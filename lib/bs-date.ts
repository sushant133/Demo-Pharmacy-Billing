export interface BsDate {
  year: number;
  month: number;
  day: number;
}

function yearRow(year: number): readonly number[] | undefined {
  return MONTHS[year - 2000];
}

function daysInBsMonth(year: number, month: number): number {
  const row = yearRow(year);
  return row?.[month] ?? 30;
}

function isGregorianLeap(year: number): boolean {
  return year % 400 === 0 || (year % 100 !== 0 && year % 4 === 0);
}

function daysInGregorianMonth(year: number, month: number): number {
  const table = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  if (month === 2 && isGregorianLeap(year)) return 29;
  return table[month] ?? 30;
}

/**
 * Convert a Gregorian civil date to Bikram Sambat.
 * Month is 1–12. Range: 1944-01-01 through 2099 AD.
 */
export function adToBs(year: number, month: number, day: number): BsDate {
  const y0 = 1944;
  const m0 = 1;
  const d0 = 1;
  const bsY0 = 2000;
  const bsM0 = 9;
  const bsD0 = 17;

  let elapsed = 0;
  for (let y = y0; y < year; y++) elapsed += isGregorianLeap(y) ? 366 : 365;
  for (let m = 1; m < month; m++) elapsed += daysInGregorianMonth(year, m);
  elapsed += day - 1;

  let origin = 0;
  for (let m = 1; m < m0; m++) origin += daysInGregorianMonth(y0, m);
  origin += d0 - 1;

  const remaining = elapsed - origin;
  let y = bsY0;
  let m = bsM0;
  let d = bsD0 + remaining;

  while (true) {
    const dim = daysInBsMonth(y, m);
    if (d <= dim) break;
    d -= dim;
    m += 1;
    if (m > 12) {
      y += 1;
      m = 1;
    }
  }

  return { year: y, month: m, day: d };
}

/** Nepal fiscal year: 1 Shrawan to end of Ashadh, printed 2082-83. */
export function nepaliFiscalYear(bs: BsDate): string {
  const start = bs.month >= 4 ? bs.year : bs.year - 1;
  return `${start}-${String(start + 1).slice(-2)}`;
}

export function formatBs(bs: BsDate): string {
  const month = MONTH_EN[bs.month - 1] ?? String(bs.month);
  const dd = String(bs.day).padStart(2, "0");
  return `${dd} ${month} ${bs.year}`;
}

export function formatBsIso(bs: BsDate): string {
  return `${bs.year}-${String(bs.month).padStart(2, "0")}-${String(bs.day).padStart(2, "0")}`;
}
